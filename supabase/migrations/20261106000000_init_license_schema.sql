-- Supabase / PostgreSQL Schema for Chess Stealth Pro License System
-- Supports 3 license types: trial_24h, monthly, lifetime

CREATE TABLE IF NOT EXISTS public.licenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key TEXT NOT NULL UNIQUE,
    type TEXT NOT NULL CHECK (type IN ('trial_24h', 'monthly', 'lifetime')),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked', 'expired')),
    hwid TEXT DEFAULT NULL,
    hwid_reset_count INTEGER NOT NULL DEFAULT 0,
    hwid_last_reset_at BIGINT DEFAULT NULL,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW())::BIGINT),
    activated_at BIGINT DEFAULT NULL,
    expires_at BIGINT DEFAULT NULL
);

CREATE INDEX IF NOT EXISTS idx_licenses_key ON public.licenses(key);
CREATE INDEX IF NOT EXISTS idx_licenses_hwid ON public.licenses(hwid);

CREATE TABLE IF NOT EXISTS public.activation_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id BIGINT NOT NULL REFERENCES public.licenses(id) ON DELETE CASCADE,
    hwid TEXT NOT NULL,
    ip TEXT NOT NULL,
    app_version TEXT NOT NULL,
    action TEXT NOT NULL DEFAULT 'verify',
    timestamp BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW())::BIGINT)
);

CREATE INDEX IF NOT EXISTS idx_activation_logs_license_id ON public.activation_logs(license_id);

CREATE TABLE IF NOT EXISTS public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id BIGINT NOT NULL REFERENCES public.licenses(id) ON DELETE CASCADE,
    amount NUMERIC(12, 2) NOT NULL,
    method TEXT NOT NULL,
    webhook_ref TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL CHECK (status IN ('pending', 'completed', 'failed', 'refunded')),
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW())::BIGINT)
);

CREATE TABLE IF NOT EXISTS public.free_key_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip TEXT NOT NULL,
    token TEXT NOT NULL UNIQUE,
    hwid TEXT DEFAULT NULL,
    license_id BIGINT REFERENCES public.licenses(id) ON DELETE CASCADE,
    claimed_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW())::BIGINT),
    expires_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_free_key_claims_ip ON public.free_key_claims(ip);
CREATE INDEX IF NOT EXISTS idx_free_key_claims_token ON public.free_key_claims(token);

