def get_connection():
    db_file = os.environ.get("CHESSPRO_DB_PATH", DEFAULT_DB_PATH)
    os.makedirs(os.path.dirname(db_file), exist_ok=True)
    conn = sqlite3.connect(db_file, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON;")
    conn.executescript(EMBEDDED_SCHEMA_SQL)
    return conn


def init_db() -> None:
    with get_connection() as conn:
        conn.executescript(EMBEDDED_SCHEMA_SQL)
        conn.commit()
    return

    db_file = os.environ.get("CHESSPRO_DB_PATH", DEFAULT_DB_PATH)
    os.makedirs(os.path.dirname(db_file), exist_ok=True)
    with get_connection() as conn:
        if os.path.exists(SCHEMA_PATH):
            with open(SCHEMA_PATH, "r", encoding="utf-8") as f:
                conn.executescript(f.read())
        else:
            conn.executescript(EMBEDDED_SCHEMA_SQL)
        conn.commit()


def cleanup_expired_records(conn) -> None:
    now = int(time.time())
    conn.execute(
        """
        UPDATE licenses
        SET status = 'expired'
        WHERE status = 'active' AND expires_at IS NOT NULL AND expires_at <= ?
        """,
        (now,),
    )
    conn.execute(
        """
        DELETE FROM free_key_claims
        WHERE expires_at <= ?
        """,
        (now,),
    )
    conn.commit()


def generate_formatted_key(license_type: str) -> str:
    prefix_map = {
        "trial_24h": "FREE24H",
        "monthly": "PRO30D",
        "lifetime": "LIFEVIP",
    }
    prefix = prefix_map.get(license_type, "FREE24H")
    token_id = secrets.token_hex(3).upper()
    now = int(time.time())
    if license_type == "lifetime" or prefix == "LIFEVIP":
        exp_hex = "FFFFFFFF"
    elif license_type == "monthly" or prefix == "PRO30D":
        exp_hex = f"{now + 30 * 86400:08X}"
    else:
        exp_hex = f"{now + 86400:08X}"

    hmac_secret_env = os.environ.get("CHESS_PRO_HMAC_SECRET")
    if hmac_secret_env:
        sig = (
            hmac.new(
                hmac_secret_env.encode("utf-8"),
                f"KEY:{token_id}:{exp_hex}".encode("utf-8"),
                hashlib.sha256,
            )
            .hexdigest()
            .upper()[:12]
        )
    else:
        # Sử dụng entropy ngẫu nhiên mật mã học an toàn khi không cấu hình server HMAC secret
        sig = secrets.token_hex(6).upper()
    return f"{prefix}-{token_id}-{exp_hex}-{sig}"


def create_license_record(
    conn,
    license_type: str,
    custom_key: Optional[str] = None,
    hwid: Optional[str] = None,
    activate_immediately: bool = False,
) -> dict:
    now = int(time.time())
    key_str = custom_key or generate_formatted_key(license_type)

    activated_at = now if activate_immediately else None
    expires_at = None
    if activate_immediately:
        if license_type == "trial_24h":
            expires_at = now + 86400
        elif license_type == "monthly":
            expires_at = now + (30 * 86400)

    cursor = conn.execute(
        """
        INSERT INTO licenses (key, type, status, hwid, hwid_reset_count, created_at, activated_at, expires_at)
        VALUES (?, ?, 'active', ?, 0, ?, ?, ?)
        """,
        (key_str, license_type, hwid, now, activated_at, expires_at),
    )
    conn.commit()
    row = conn.execute("SELECT * FROM licenses WHERE id = ?", (cursor.lastrowid,)).fetchone()
    return dict(row)


def ensure_web24h_key_in_db(conn, clean_key: str, hwid_hint: str | None = None) -> Optional[dict]:
    """
    Tra cứu hoặc đồng bộ license key hợp lệ vào cơ sở dữ liệu:
    1. Kiểm tra trong SQLite licenses cục bộ trước tiên.
    2. Nếu chưa có, đồng bộ qua Cloudflare Worker API chính thức (https://chess-stealth-key-api.quitworks.workers.dev).
    3. Nếu không có mạng, kiểm tra xác thực chữ ký HMAC-SHA256 ngoại tuyến (Offline Fallback).
    Tự động lưu vào SQLite licenses để kích hoạt và sử dụng ngay lập tức.
    """
    clean = clean_key.strip().upper()
    existing = conn.execute(
        "SELECT * FROM licenses WHERE UPPER(TRIM(key)) = UPPER(TRIM(?))", (clean,)
    ).fetchone()
    if existing:
        return dict(existing)

    parts = clean.split("-")
    if len(parts) != 4:
        return None
    prefix, token_id, exp_hex, key_sig = parts
    if prefix not in ("FREE24H", "PRO07D", "PRO30D", "LIFEVIP"):
        return None
    if len(token_id) != 6 or len(exp_hex) != 8 or len(key_sig) != 6:
        return None

    worker_checked = False
    worker_valid = False
    worker_hwid = None
    try:
        hwid_param = f"&hwid={urllib.parse.quote(hwid_hint.strip().upper())}" if hwid_hint else ""
        url = f"https://chess-stealth-key-api.quitworks.workers.dev/api/check-key?key={urllib.parse.quote(clean)}{hwid_param}"
        req = urllib.request.Request(
            url,
            headers={"User-Agent": "ChessStealthPro/2.0.0", "Accept": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=3.5) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            worker_checked = True
            if data.get("valid") is True and not data.get("revoked"):
                worker_valid = True
                worker_hwid = data.get("hwid")
            else:
                return None
    except Exception:
        pass

    if not worker_valid:
        if worker_checked:
            return None
        secret = os.environ.get("CHESS_PRO_HMAC_SECRET", "CHESS_STEALTH_PRO_WEB24H_SECRET_2026")
        if isinstance(secret, str):
            secret = secret.encode("utf-8")
        expected_sig = (
            hmac.new(secret, f"KEY:{token_id}:{exp_hex}".encode("utf-8"), hashlib.sha256)
            .hexdigest()[:6]
            .upper()
        )
        if not hmac.compare_digest(key_sig, expected_sig):
            return None

    is_lifetime = (prefix == "LIFEVIP" or exp_hex == "FFFFFFFF")
    exp_ts = None
    if not is_lifetime:
        try:
            exp_ts = int(exp_hex, 16)
            if exp_ts <= int(time.time()):
                return None
        except ValueError:
            return None

    if prefix == "FREE24H":
        ltype = "trial_24h"
    elif prefix == "LIFEVIP":
        ltype = "lifetime"
    else:
        ltype = "monthly"

    now = int(time.time())
    cursor = conn.execute(
        """
        INSERT INTO licenses (key, type, status, hwid, hwid_reset_count, created_at, activated_at, expires_at)
        VALUES (?, ?, 'active', ?, 0, ?, NULL, ?)
        """,
        (clean, ltype, worker_hwid, now, exp_ts),
    )
    conn.commit()
    row = conn.execute("SELECT * FROM licenses WHERE id = ?", (cursor.lastrowid,)).fetchone()
    return dict(row) if row else None

